'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('gitnest', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  addRoot: (p) => ipcRenderer.invoke('roots:add', p),
  removeRepo: (p) => ipcRenderer.invoke('repos:remove', p),
  pickFolder: () => ipcRenderer.invoke('dialog:pickFolder'),
  scan: () => ipcRenderer.invoke('repos:scan'),
  statuses: (paths) => ipcRenderer.invoke('repos:statuses', paths),
  status: (repo) => ipcRenderer.invoke('repo:status', repo),
  files: (repo) => ipcRenderer.invoke('repo:files', repo),
  stage: (repo, paths) => ipcRenderer.invoke('repo:stage', repo, paths),
  unstage: (repo, paths) => ipcRenderer.invoke('repo:unstage', repo, paths),
  commit: (repo, message) => ipcRenderer.invoke('repo:commit', repo, message),
  push: (repo) => ipcRenderer.invoke('repo:push', repo),
  pull: (repo) => ipcRenderer.invoke('repo:pull', repo),
  fetch: (repo) => ipcRenderer.invoke('repo:fetch', repo),
  log: (repo, paths) => ipcRenderer.invoke('repo:log', repo, paths),
  logRange: (repo, range) => ipcRenderer.invoke('repo:logrange', repo, range),
  show: (repo, hash) => ipcRenderer.invoke('repo:show', repo, hash),
  diff: (repo, paths, cached) => ipcRenderer.invoke('repo:diff', repo, paths, cached),
  commitDiff: (repo, hash, paths) => ipcRenderer.invoke('repo:commitdiff', repo, hash, paths),
  branches: (repo) => ipcRenderer.invoke('repo:branches', repo),
  checkout: (repo, name) => ipcRenderer.invoke('repo:checkout', repo, name),
  createBranch: (repo, name) => ipcRenderer.invoke('repo:createbranch', repo, name),
  deleteBranch: (repo, name) => ipcRenderer.invoke('repo:deletebranch', repo, name),
  merge: (repo, name) => ipcRenderer.invoke('repo:merge', repo, name),
  revert: (repo, paths) => ipcRenderer.invoke('repo:revert', repo, paths),
  revertCommit: (repo, hash) => ipcRenderer.invoke('repo:revertcommit', repo, hash),
  cherryPick: (repo, hash) => ipcRenderer.invoke('repo:cherrypick', repo, hash),
  stashList: (repo) => ipcRenderer.invoke('repo:stashlist', repo),
  stash: (repo, paths) => ipcRenderer.invoke('repo:stash', repo, paths),
  stashPop: (repo) => ipcRenderer.invoke('repo:stashpop', repo),
  popupHistoryMenu: (repo, hash, subject, behind) => ipcRenderer.invoke('menu:history', repo, hash, subject, behind),
  copyCherry: (repo, hash) => ipcRenderer.invoke('cherry:copy', repo, hash),
  getCherryClipboard: () => ipcRenderer.invoke('cherry:clipboard'),
  popupChangesMenu: (n) => ipcRenderer.invoke('menu:changes', n),
  openInEditor: (repo, relPath) => ipcRenderer.invoke('repo:openineditor', repo, relPath),
  getOpLog: () => ipcRenderer.invoke('git:oplog'),
  onOp: (cb) => ipcRenderer.on('git:op', (e, entry) => cb(entry)),
  setConfig: (patch) => ipcRenderer.invoke('config:set', patch),
  pickEditor: () => ipcRenderer.invoke('dialog:pickEditor'),
});
